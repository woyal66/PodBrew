const SCHEDULER_INTERVAL_MS = 60 * 1000; // Check every minute
const RESUMABLE_GEN_INTERVAL_MS = 30 * 1000; // Process pending generations every 30 seconds
const CLEANUP_INTERVAL_MS = 60 * 60 * 1000; // Run cleanup every hour

let schedulerInterval: NodeJS.Timeout | null = null;
let cleanupInterval: NodeJS.Timeout | null = null;
let resumableGenInterval: NodeJS.Timeout | null = null;

interface SchedulerContext {
  generatePodcast: (params: GeneratePodcastParams) => Promise<any>;
}

interface GeneratePodcastParams {
  userId: string;
  topic: string;
  templateCategory: string;
  durationMinutes: number;
  languageComplexity: number;
  numPeople: number;
  podcastStyle: string;
  coHostPersonality: string;
  podcastMood: string;
  language: string;
  selectedVoiceIds: string[];
  isPublic: boolean;
  previousScriptSummary?: string;
  creditCost: number; // Credits already deducted before generation
  musicStyle?: string; // Lyria 3 background music style
}

function getTimeInTimezone(timezone: string): { hours: number; minutes: number } {
  try {
    const now = new Date();
    const formatter = new Intl.DateTimeFormat('en-US', {
      timeZone: timezone,
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    });
    const parts = formatter.formatToParts(now);
    const hours = parseInt(parts.find(p => p.type === 'hour')?.value || '0');
    const minutes = parseInt(parts.find(p => p.type === 'minute')?.value || '0');
    return { hours, minutes };
  } catch (error) {
    console.error(`[Scheduler] Invalid timezone: ${timezone}, defaulting to UTC`);
    const now = new Date();
    return { hours: now.getUTCHours(), minutes: now.getUTCMinutes() };
  }
}

function getDateInTimezone(timezone: string): string {
  try {
    const now = new Date();
    const formatter = new Intl.DateTimeFormat('en-US', {
      timeZone: timezone,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    });
    return formatter.format(now);
  } catch (error) {
    return new Date().toISOString().split('T')[0];
  }
}

function isDueForGeneration(preset: NewsPreset): boolean {
  if (!preset.autoGenerateEnabled || !preset.autoGenerateTime) {
    return false;
  }

  const timezone = preset.autoGenerateTimezone || 'UTC';
  const [targetHour, targetMinute] = preset.autoGenerateTime.split(':').map(Number);
  const { hours: currentHour, minutes: currentMinute } = getTimeInTimezone(timezone);

  // Check if we're within the target minute window
  const isTimeMatch = currentHour === targetHour && currentMinute === targetMinute;
  if (!isTimeMatch) {
    return false;
  }

  // Check if we've already generated today in this timezone
  if (preset.lastAutoGeneratedAt) {
    const lastGenDate = new Date(preset.lastAutoGeneratedAt);
    const todayDateStr = getDateInTimezone(timezone);
    
    // Format last generation date in the target timezone and compare to today
    const lastGenFormatter = new Intl.DateTimeFormat('en-US', {
      timeZone: timezone,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    });
    const lastGenFormatted = lastGenFormatter.format(lastGenDate);
    
    if (lastGenFormatted === todayDateStr) {
      return false; // Already generated today
    }
  }

  return true;
}

async function runAutoGeneration(
  preset: NewsPreset, 
  topics: FavoriteTopic[],
  context: SchedulerContext
): Promise<void> {
  const userId = preset.userId;
  const durationMinutes = preset.durationMinutes || 5;
  console.log(`[Scheduler] Starting auto-generation for user ${userId}`);

  // Guard: orphaned/guest presets without a userId can't deduct credits or own podcasts
  if (!userId) {
    console.warn(`[Scheduler] Preset ${preset.id} has no userId - skipping auto-generation`);
    await storage.updateAutoGenerateStatus(preset.id, 'skipped', 'Preset has no user');
    return;
  }

  // Check if there are topics to generate from first (no credit cost)
  if (topics.length === 0) {
    console.log(`[Scheduler] User ${userId} has no favorite topics`);
    await storage.updateAutoGenerateStatus(preset.id, 'skipped', 'No favorite topics configured');
    return;
  }

  // Calculate credit cost (0.1 credits per minute for premium voices)
  const creditCost = durationMinutes * 0.1;
  
  try {
    // Deduct credits atomically BEFORE generation
    console.log(`[Scheduler] Deducting ${creditCost.toFixed(1)} credits from user ${userId}`);
    await checkAndDeductCreditsAtomic(userId, creditCost);
  } catch (error: any) {
    if (error instanceof InsufficientCreditsError) {
      console.log(`[Scheduler] User ${userId} has insufficient credits: ${error.message}`);
      await storage.updateAutoGenerateStatus(preset.id, 'insufficient_credits', error.message);
      return;
    }
    throw error;
  }

  try {
    // Build the topic string
    const combinedTopic = `Daily Personalized News Brief covering: ${topics.map(t => t.label).join('; ')}. Provide updates on each topic with the latest news and developments.`;

    // Generate the podcast (credits already deducted)
    const result = await context.generatePodcast({
      userId,
      topic: combinedTopic,
      templateCategory: 'news',
      durationMinutes,
      languageComplexity: preset.languageComplexity || 6,
      numPeople: preset.numPeople || 1,
      podcastStyle: preset.podcastStyle || 'news',
      coHostPersonality: preset.coHostPersonality || 'executive',
      podcastMood: preset.podcastMood || 'balanced',
      language: preset.language || 'en',
      selectedVoiceIds: preset.selectedVoiceIds || [],
      isPublic: preset.autoGeneratePublic ?? true,
      previousScriptSummary: preset.lastGeneratedScriptSummary || undefined,
      creditCost, // Pass the credit cost for podcast record
    });

    console.log(`[Scheduler] Auto-generation completed for user ${userId}, credits deducted: ${creditCost.toFixed(1)}`);
    await storage.updateAutoGenerateStatus(preset.id, 'success');

  } catch (error: any) {
    console.error(`[Scheduler] Auto-generation failed for user ${userId}:`, error);
    
    // Refund credits on failure
    try {
      await refundCredits(userId, creditCost);
      console.log(`[Scheduler] Refunded ${creditCost.toFixed(1)} credits to user ${userId} due to generation failure`);
    } catch (refundError) {
      console.error(`[Scheduler] Failed to refund credits to user ${userId}:`, refundError);
    }
    
    await storage.updateAutoGenerateStatus(preset.id, 'failed', error.message || 'Unknown error');
  }
}

