function getNextEpisodeToGenerate(syllabus: SyllabusEpisode[]): SyllabusEpisode | null {
  // Find the first episode that hasn't been generated yet
  return syllabus.find(ep => !ep.generated) || null;
}

async function runTeachMeAutoGeneration(
  preset: TeachmePreset,
  context: SchedulerContext
): Promise<void> {
  const userId = preset.userId;
  const durationMinutes = preset.episodeDuration || 10;
  console.log(`[Scheduler] Starting TeachMe auto-generation for user ${userId}, course: ${preset.name}`);

  // Guard: orphaned/guest presets without a userId can't deduct credits or own podcasts
  if (!userId) {
    console.warn(`[Scheduler] TeachMe preset ${preset.id} has no userId - skipping auto-generation`);
    await storage.updateTeachmeAutoGenerateStatus(preset.id, 'skipped', 'Preset has no user');
    return;
  }

  // Parse syllabus
  const syllabus = preset.syllabus as SyllabusEpisode[];
  if (!syllabus || !Array.isArray(syllabus)) {
    console.log(`[Scheduler] TeachMe preset ${preset.id} has invalid syllabus`);
    await storage.updateTeachmeAutoGenerateStatus(preset.id, 'failed', 'Invalid syllabus');
    return;
  }

  // Find next episode to generate
  const nextEpisode = getNextEpisodeToGenerate(syllabus);
  if (!nextEpisode) {
    console.log(`[Scheduler] TeachMe course ${preset.id} is complete, all episodes generated`);
    // Mark course as complete and deactivate
    await storage.updateTeachmePreset(preset.id, userId, { isActive: false });
    await storage.updateTeachmeAutoGenerateStatus(preset.id, 'success', 'Course completed');
    return;
  }

  // Calculate credit cost (0.1 credits per minute for premium voices)
  const creditCost = durationMinutes * 0.1;
  
  try {
    // Deduct credits atomically BEFORE generation
    console.log(`[Scheduler] Deducting ${creditCost.toFixed(1)} credits from user ${userId} for TeachMe episode ${nextEpisode.episodeNumber}`);
    await checkAndDeductCreditsAtomic(userId, creditCost);
  } catch (error: any) {
    if (error instanceof InsufficientCreditsError) {
      console.log(`[Scheduler] User ${userId} has insufficient credits for TeachMe: ${error.message}`);
      await storage.updateTeachmeAutoGenerateStatus(preset.id, 'insufficient_credits', error.message);
      return;
    }
    throw error;
  }

  try {
    // Build the episode topic with context from the course
    const totalEpisodes = syllabus.length;
    const episodeTopic = `Episode ${nextEpisode.episodeNumber}/${totalEpisodes}: ${nextEpisode.title}

Course: ${preset.topic}
Episode Focus: ${nextEpisode.focusTopic}
Key Points to Cover:
${nextEpisode.keyPoints.map((kp, i) => `${i + 1}. ${kp}`).join('\n')}

This is part of a ${totalEpisodes}-episode educational course. Make sure to provide a brief recap of the previous episode if applicable and a preview of what's coming next.`;

    // Generate the podcast (credits already deducted)
    const result = await context.generatePodcast({
      userId,
      topic: episodeTopic,
      templateCategory: 'teachme',
      durationMinutes,
      languageComplexity: preset.languageComplexity || 6,
      numPeople: preset.numPeople || 2,
      podcastStyle: preset.podcastStyle || 'conversational',
      coHostPersonality: preset.coHostPersonality || 'academic',
      podcastMood: preset.podcastMood || 'balanced',
      language: preset.language || 'en',
      selectedVoiceIds: preset.selectedVoiceIds || [],
      isPublic: preset.autoGeneratePublic ?? true,
      creditCost, // Pass the credit cost for podcast record
    });

    // Update syllabus with generated episode info using markTeachmeEpisodeGenerated
    await storage.markTeachmeEpisodeGenerated(preset.id, nextEpisode.episodeNumber, result.id);

    // Check if this was the last episode
    const remainingEpisodes = syllabus.filter(ep => !ep.generated && ep.episodeNumber !== nextEpisode.episodeNumber).length;
    if (remainingEpisodes === 0) {
      console.log(`[Scheduler] TeachMe course ${preset.id} completed all ${totalEpisodes} episodes`);
      await storage.updateTeachmePreset(preset.id, userId, { isActive: false });
    }

    console.log(`[Scheduler] TeachMe auto-generation completed for user ${userId}, episode ${nextEpisode.episodeNumber}/${totalEpisodes}`);
    await storage.updateTeachmeAutoGenerateStatus(preset.id, 'success');

  } catch (error: any) {
    console.error(`[Scheduler] TeachMe auto-generation failed for user ${userId}:`, error);
    
    // Refund credits on failure
    try {
      await refundCredits(userId, creditCost);
      console.log(`[Scheduler] Refunded ${creditCost.toFixed(1)} credits to user ${userId} due to TeachMe generation failure`);
    } catch (refundError) {
      console.error(`[Scheduler] Failed to refund credits to user ${userId}:`, refundError);
    }
    
    await storage.updateTeachmeAutoGenerateStatus(preset.id, 'failed', error.message || 'Unknown error');
  }
}

async function checkAutoGenerationJobs(context: SchedulerContext): Promise<void> {
  try {
    // Check News presets
    const enabledPresets = await storage.getAutoGeneratePresets();
    
    for (const preset of enabledPresets) {
      if (isDueForGeneration(preset)) {
        console.log(`[Scheduler] News Preset ${preset.id} is due for auto-generation`);

        // Skip orphaned presets without a userId (favorite topics require a userId)
        if (!preset.userId) {
          console.warn(`[Scheduler] News Preset ${preset.id} has no userId - skipping`);
          continue;
        }

        // Get user's favorite topics
        const topics = await storage.listFavoriteTopics(preset.userId);
        
        // Run generation (don't await to avoid blocking other checks)
        runAutoGeneration(preset, topics, context).catch(err => {
          console.error(`[Scheduler] Failed to run auto-generation for preset ${preset.id}:`, err);
        });
      }
    }

    // Check TeachMe presets for Daily Micro-Learning
    const enabledTeachMePresets = await storage.getAutoGenerateTeachmePresets();
    
    for (const preset of enabledTeachMePresets) {
      if (isTeachMeDueForGeneration(preset)) {
        console.log(`[Scheduler] TeachMe Preset ${preset.id} is due for auto-generation`);
        
        // Run generation (don't await to avoid blocking other checks)
        runTeachMeAutoGeneration(preset, context).catch(err => {
          console.error(`[Scheduler] Failed to run TeachMe auto-generation for preset ${preset.id}:`, err);
        });
      }
    }
  } catch (error) {
    console.error('[Scheduler] Error checking auto-generation jobs:', error);
  }
}

async function runCleanupJobs(): Promise<void> {
  console.log('[Scheduler] Running cleanup jobs...');
  
  try {
    const result = await podcastCleanupService.runFullCleanup();
    
    console.log('[Scheduler] Cleanup jobs completed:', {
      news: {
        deleted: result.news.podcastsDeleted,
        audioFiles: result.news.audioFilesDeleted,
        coverImages: result.news.coverImagesDeleted,
        errors: result.news.errors.length
      },
      lowEngagement: {
        deleted: result.lowEngagement.podcastsDeleted,
        audioFiles: result.lowEngagement.audioFilesDeleted,
        coverImages: result.lowEngagement.coverImagesDeleted,
        errors: result.lowEngagement.errors.length
      }
    });
    
    // Cleanup expired trial podcasts from guests who didn't sign up
    const trialCleanupResult = await cleanupExpiredTrialPodcasts();
    if (trialCleanupResult.deleted > 0) {
      console.log(`[Scheduler] Trial cleanup: deleted ${trialCleanupResult.deleted} expired trial podcasts`);
    }
  } catch (error) {
    console.error('[Scheduler] Error running cleanup jobs:', error);
  }
}

export function startScheduler(context: SchedulerContext): void {
  if (schedulerInterval) {
    console.log('[Scheduler] Scheduler already running');
    return;
  }

  console.log('[Scheduler] Starting auto-generation scheduler (1-minute interval)');
  
  // Run auto-generation check every minute
  schedulerInterval = setInterval(() => {
    checkAutoGenerationJobs(context);
  }, SCHEDULER_INTERVAL_MS);

  // Run cleanup every hour
  console.log('[Scheduler] Starting cleanup scheduler (1-hour interval)');
  cleanupInterval = setInterval(() => {
    runCleanupJobs();
  }, CLEANUP_INTERVAL_MS);

  // Run initial cleanup on startup (after a short delay to let server settle)
  setTimeout(() => {
    runCleanupJobs();
  }, 10000);
}

export function stopScheduler(): void {
  if (schedulerInterval) {
    clearInterval(schedulerInterval);
    schedulerInterval = null;
    console.log('[Scheduler] Auto-generation scheduler stopped');
  }
  if (cleanupInterval) {
    clearInterval(cleanupInterval);
    cleanupInterval = null;
    console.log('[Scheduler] Cleanup scheduler stopped');
  }
  if (resumableGenInterval) {
    clearInterval(resumableGenInterval);
    resumableGenInterval = null;
    console.log('[Scheduler] Resumable generation scheduler stopped');
  }
}

/**
 * Process pending podcast generations (resumable, checkpoint-based)
 */
async function processPendingGenerations(): Promise<void> {
  try {
    const pendingJobs = await getPendingJobs();
    
    if (pendingJobs.length === 0) {
      return;
    }
    
    console.log(`[Scheduler] Processing ${pendingJobs.length} pending generation(s)...`);
    
    // Process one batch per job (prevents blocking)
    for (const job of pendingJobs) {
      try {
        const done = await processJobBatch(job.id);
        if (done) {
          console.log(`[Scheduler] Job ${job.id} completed`);
        }
      } catch (error) {
        console.error(`[Scheduler] Error processing job ${job.id}:`, error);
      }
      // Only process one batch per interval to allow server to respond to other requests
      break;
    }
  } catch (error) {
    console.error('[Scheduler] Error in pending generation processing:', error);
  }
}

/**
 * Start the resumable generation scheduler
 */
export function startResumableGenScheduler(): void {
  console.log('[Scheduler] Starting resumable generation scheduler (30-second interval)');
  
  // Process pending jobs every 30 seconds
  resumableGenInterval = setInterval(() => {
    processPendingGenerations();
  }, RESUMABLE_GEN_INTERVAL_MS);
  
  // Also check for pending jobs on startup (after a short delay)
  setTimeout(() => {
    console.log('[Scheduler] Checking for pending jobs on startup...');
    resumePendingJobs();
  }, 5000);
}

export async function runCatchUpJobs(userId: string, context: SchedulerContext): Promise<void> {
  console.log(`[Scheduler] Running catch-up jobs for user ${userId}`);
  
  try {
    // Check if user has an auto-generate preset that missed a run
    const preset = await storage.getNewsPreset(userId);
    
    if (preset?.autoGenerateEnabled && preset.autoGenerateTime) {
      const timezone = preset.autoGenerateTimezone || 'UTC';
      const [targetHour] = preset.autoGenerateTime.split(':').map(Number);
      const { hours: currentHour } = getTimeInTimezone(timezone);
      
      // Check if we're within 3 hours after the scheduled time
      const hoursSinceScheduled = (currentHour - targetHour + 24) % 24;
      
      if (hoursSinceScheduled > 0 && hoursSinceScheduled <= 3) {
        // Check if we haven't generated today
        const todayDateStr = getDateInTimezone(timezone);
        
        if (preset.lastAutoGeneratedAt) {
          const lastGenFormatter = new Intl.DateTimeFormat('en-US', {
            timeZone: timezone,
            year: 'numeric',
            month: '2-digit',
            day: '2-digit',
          });
          const lastGenFormatted = lastGenFormatter.format(new Date(preset.lastAutoGeneratedAt));
          
          if (lastGenFormatted === todayDateStr) {
            console.log(`[Scheduler] User ${userId} already generated today, skipping catch-up`);
            return;
          }
        }
        
        console.log(`[Scheduler] User ${userId} missed scheduled generation, running catch-up`);
        const topics = await storage.listFavoriteTopics(userId);
        await runAutoGeneration(preset, topics, context);
      }
    }
  } catch (error) {
    console.error(`[Scheduler] Error running catch-up for user ${userId}:`, error);
  }
}
